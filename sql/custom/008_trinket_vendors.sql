--  66 trinkets are deliberately absent: they have buy_price = 0 and a vendor
--  cannot sell a zero-price item - it simply would not appear in the window.
--  That includes all 5 artifact-quality (q6) trinkets. Use .additem for those.
--  No QA/test/placeholder junk needed filtering; none of it is purchasable.
--
--  Re-runnable. Apply with:
--    DB\bin\mariadb.exe -h 127.0.0.1 -P 3307 -u root tw_world < sql\custom\008_trinket_vendors.sql
--  then restart mangosd. Spawn with:
--    .npc add 100005      .npc add 100006      .npc add 100007
-- ============================================================================

