-- ============================================================================
--  Custom NPC: enchanting service via gossip menus  (tw_world)
-- ============================================================================
--  Magister Elandra (creature 100001). Twelve slot menus. Two kinds of entry:
--
--   1. SCROLL entries (34) - profession enchants. The purchase grants a custom
--      scroll casting the real spell, PLUS every reagent and the rod it needs.
--   2. DIRECT-ITEM entries (63) - enchants that already exist as items whose
--      spell is reagent-free (belt buckles, Zandalar signets, Scourge shoulder
--      enchants, arcanums, shield spikes, Fiery Blaze). Nothing is generated;
--      the purchase just hands over the real item.
--
--  WHY REAGENTS ARE GRANTED RATHER THAN WAIVED:
--  Enchant spells act on an ITEM target, so a usable item is unavoidable - this
--  core has 91 script commands, none of which enchant, and CAST_SPELL cannot
--  target a player's bags. Worse, the CLIENT validates reagents and the rod
--  from its own Spell.dbc before the cast is sent. There is no Spell.dbc
--  server-side (spells load from spell_template), so DB edits are invisible to
--  that check - pointing scrolls at reagent-free "QAEnchant" twins FAILED, the
--  client still demanded a Runed Arcanite Rod and Large Brilliant Shards. So we
--  give the player exactly what the client will ask for. Rods are not consumed
--  and not unique; one comes with every scroll purchase, spares can be dropped.
--
--  NOTE ON npc_option_npcflag: MUST be non-zero and match a flag the creature
--  has (1 = gossip). 0 does NOT mean "no restriction" - the option is silently
--  filtered at runtime and never rendered, with no load error.
--
--  NOTE ON PRICING: box_money is NOT used. It is read by the core, but not one
--  of the 2724 stock gossip options in this DB sets it, and options carrying it
--  rendered with a quest "!" icon instead of a chat bubble - a money field in
--  the gossip packet is a TBC-era addition this 1.12 client mis-parses. Every
--  purchase is therefore FREE; the price still shows in the option label as a
--  guide. To restore charging, add a box_money column to the purchase INSERT
--  below with the value from the label.
--
--  ID BLOCKS: creature 100001 | scroll items 100001-100034
--             menus 64000-64015 (64015 is a Back-target copy of the root) | npc_text / broadcast_text 6400000-6400014
--             scripts 6400001-6400034 (scrolls), 6400051+ (direct items)
--  gossip_menu.entry is smallint and nearly exhausted; 64000-64997 was free.
--
--  MENU SIZE LIMIT - measure SUM(CHAR_LENGTH(option_text) + 7), not text alone.
--  The 7 is the per-option overhead in the gossip packet (index, icon, coded,
--  string terminator). Past about 512 bytes the client stops parsing options
--  early and reads the remaining bytes as the QUEST list: the tail of the menu
--  appears above the options with quest "!" icons and titles cut off mid-word.
--  Measured here: 467 bytes renders fine, 526 does not. Keep every menu under
--  ~490 and split a category across two menus when it grows past that. Shoulder
--  and head/leg are both split for this reason.
--  Prices are NOT in the labels: purchases are free, and the suffix wasted
--  budget that the limit above makes precious.
--
--  Apply, then RESTART mangosd. Spawn with:  .npc add 100001
-- ============================================================================

